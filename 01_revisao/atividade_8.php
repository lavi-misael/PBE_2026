<?php
    $operacao = "+";
    $num1 = 8;
    $num2 = 5;

    switch ($operacao){
        case "+":
            echo $num1 + $num2;
            break;
        case "-":
            echo $num1 - $num2;
            break;
        case "*":
            echo $num1 * $num2;
            break;
        case  "/":
            echo $num1 / $num2;
            break;
    }
?>